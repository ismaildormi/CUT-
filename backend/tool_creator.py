def register_tool(
    name: str,
    description: str,
    service_name: str,
    script_path: str,
    parameters: Optional[Dict[str, Any]] = None
) -> Dict[str, Any]:
    """Register tool entry in dynamic_tools.json."""
    registry = get_registry()
    tools = registry.get("tools", [])

    existing_idx = next((i for i, t in enumerate(tools) if t.get("name") == name), None)
    tool_meta = {
        "name": name,
        "service": service_name,
        "description": description,
        "scriptPath": script_path,
        "parameters": parameters or {"params": "object"},
        "isDynamic": True,
    }

    if existing_idx is not None:
        tools[existing_idx] = tool_meta
    else:
        tools.append(tool_meta)

    registry["tools"] = tools
    registry["last_updated"] = os.path.getmtime(script_path)
    save_registry(registry)
    return tool_meta


def ensure_service_tool(service_name: str) -> Dict[str, Any]:
    """Check if tool exists; if missing, autonomously write, test, and register it."""
    s_clean = service_name.lower().replace("-", "_").replace(" ", "_")
    tool_name = f"{s_clean}_tool"
    script_path = os.path.join(TOOLS_DIR, f"{tool_name}.py")

    if not os.path.isfile(script_path):
        script_path = generate_tool_script(service_name)

    return register_tool(
        name=tool_name,
        description=f"Autonomous self-written tool for {service_name.capitalize()} API interaction",
        service_name=service_name,
        script_path=script_path
    )


def execute_dynamic_tool(tool_name: str, params: Dict[str, Any]) -> Dict[str, Any]:
    """Execute a dynamic tool script via subprocess."""
    s_clean = tool_name.replace(".py", "")
    script_path = os.path.join(TOOLS_DIR, f"{s_clean}.py")

    if not os.path.isfile(script_path):
        # Auto-create if missing
        ensure_service_tool(s_clean.replace("_tool", ""))

    python_cmd = sys.executable or "python3"
    proc = subprocess.run(
        [python_cmd, script_path, json.dumps(params)],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=20
    )
    if proc.returncode == 0:
        try:
            return json.loads(proc.stdout.strip())
        except Exception:
            return {"success": True, "raw_output": proc.stdout.strip()}
    else:
        return {"success": False, "error": proc.stderr.strip() or f"Exit {proc.returncode}"}


