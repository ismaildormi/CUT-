REGISTRY_FILE = os.path.join(BASE_DIR, "dynamic_tools.json")
VAULT_FILE = os.path.join(BASE_DIR, "vault.json")

os.makedirs(TOOLS_DIR, exist_ok=True)


def get_vault_credentials() -> Dict[str, str]:
    """Retrieve all credentials stored in backend/vault.json and environment."""
    creds = {}
    if os.path.isfile(VAULT_FILE):
        try:
            with open(VAULT_FILE, "r", encoding="utf-8") as f:
                data = json.load(f)
                creds.update(data.get("credentials", {}))
                creds.update(data.get("custom_services", {}))
        except Exception:
            pass

    for k, v in os.environ.items():
        if "KEY" in k or "TOKEN" in k or "SECRET" in k:
            creds[k] = v

    return creds


def get_vault_key(service_name: str) -> str:
    """Find the API key or token for a service name from the Universal Vault."""
    s_upper = service_name.upper().replace("-", "_")
    creds = get_vault_credentials()

    candidates = [
        f"{s_upper}_API_KEY",
        f"{s_upper}_BOT_TOKEN",
        f"{s_upper}_TOKEN",
        f"{s_upper}_SECRET",
        s_upper,
    ]
    for c in candidates:
        if c in creds and creds[c]:
            return creds[c]

    for k, v in creds.items():
        if s_upper in k.upper() and v:
            return v

    return ""


def get_registry() -> Dict[str, Any]:
    """Load current dynamic tools registry."""
    if os.path.isfile(REGISTRY_FILE):
        try:
            with open(REGISTRY_FILE, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception:
            pass
    return {"tools": [], "last_updated": ""}


def save_registry(registry: Dict[str, Any]):
    """Save updated tools registry."""
    with open(REGISTRY_FILE, "w", encoding="utf-8") as f:
        json.dump(registry, f, indent=2)


